export function getTermById(id: string): Term | undefined {
  return TERMS.find((t) => t.id === id);
}

export function getTermsByCategory(category: Category | 'all'): Term[] {
  if (category === 'all') return TERMS;
  return TERMS.filter((t) => t.category === category);
}

export function getRandomTerm(excludeId?: string): Term {
  const pool = excludeId ? TERMS.filter((t) => t.id !== excludeId) : TERMS;
  return pool[Math.floor(Math.random() * pool.length)];
}

export function shuffleTerms(list: Term[] = TERMS): Term[] {
  const arr = [...list];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

export type QuizKind = 'en-to-el' | 'el-to-en' | 'meaning';

/** Κύρια αγγλική μορφή χωρίς εναλλακτικές/παρενθέσεις */
export function primaryEnglish(term: Term): string {
  return term.en.split('/')[0].replace(/\s*\(.*?\)\s*/g, '').trim();
}

export function primaryGreek(term: Term): string {
  return term.el.split('/')[0].trim();
}

/**
 * Πραγματική ερώτηση εκμάθησης — δεν αποκαλύπτει την απάντηση στην εκφώνηση.
 * π.χ. «Πώς λέγεται στα ελληνικά το Mainsheet;» και όχι «Πώς λέγεται η σκότα μαΐστρας;»
 */
export function buildQuizQuestion(
  term: Term,
  kind?: QuizKind,
): { kind: QuizKind; text: string } {
  const options: QuizKind[] = ['en-to-el', 'el-to-en', 'meaning'];
  const selected =
    kind ?? options[Math.floor(Math.random() * options.length)];

  const en = primaryEnglish(term);
  const el = primaryGreek(term);

  switch (selected) {
    case 'en-to-el':
      return {
        kind: selected,
        text: `Πώς λέγεται στα ελληνικά το «${en}»;`,
      };
    case 'el-to-en':
      return {
        kind: selected,
        text: `Πώς λέγεται στα αγγλικά το «${el}»;`,
      };
    case 'meaning':
      return {
        kind: selected,
        text: `Ποιος ναυτικός όρος ταιριάζει σε αυτή την περιγραφή;\n\n${term.meaning}`,
      };
  }
}
